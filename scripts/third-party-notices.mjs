// Regenerates THIRD_PARTY_NOTICES.md: `node scripts/third-party-notices.mjs`.
// Lists the Bushiroad notice and the licences of every package bundled into the app's renderer
// (the Electron/Chromium licences are added to release builds by electron-builder itself).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BUNDLED = ['react', 'react-dom', 'scheduler', '@fontsource/orbitron', '@fontsource/rajdhani'];

const read = (pkg, file) => readFileSync(join('node_modules', pkg, file), 'utf8');
const sections = BUNDLED.map((pkg) => {
  const meta = JSON.parse(read(pkg, 'package.json'));
  const licence = read(pkg, 'LICENSE').trim();
  return `## ${pkg} ${meta.version}\n\nLicence: ${meta.license}\n\n\`\`\`text\n${licence}\n\`\`\`\n`;
});

const text = `# Third-party notices

## Cardfight!! Vanguard

Cardfight!! Vanguard and all related names, card names, card text, card data, artwork and logos are
trademarks and copyrights of Bushiroad Inc. This is an unofficial, non-commercial fan project. It is
not produced, endorsed, supported or affiliated with Bushiroad. The GPL-3.0 licence of this
project covers only its own source code, not Bushiroad's material. No card artwork is included in
this repository or in its releases. Card names, statistics and text are included so the simulator
can be played; they remain Bushiroad's property and will be removed on request from the rights
holder.

## Software bundled in the application

Generated by \`node scripts/third-party-notices.mjs\` from the installed packages. Release builds
also contain Electron (MIT, \`LICENSE.electron.txt\`) and Chromium's licences
(\`LICENSES.chromium.html\`), added by electron-builder.

${sections.join('\n')}`;

writeFileSync('THIRD_PARTY_NOTICES.md', text);
console.log(`THIRD_PARTY_NOTICES.md: ${BUNDLED.length} packages`);
