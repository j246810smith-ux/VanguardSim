"""Builds data/releases.json and data/decks/library.json. Deck contents come only from the extracted
sources (data/raw/decks/candidates.json), so no count is ever typed by hand; data/decks/selection.json
says which lists to take and what is known about them.

    python scripts/decks/extractLists.py && python scripts/decks/buildLibrary.py
"""
import json
import re
import sys

JP_PRODUCTS = 'data/raw/decks/jp-products.json'


def build_releases():
    items = json.load(open(JP_PRODUCTS, encoding='utf-8'))['items']
    sets = {}
    for p in items:
        m = re.match(r'【((?:BT|TD|EB|FC|DG|MBT|MTD)\d{2}|VZ)】', p['name'])
        if m:
            sets['VZ01' if m[1] == 'VZ' else m[1]] = {'jp': p['release_date'], 'en': None}
            continue
        y = re.match(r'【20(1[1-4])年度】PR', p['name'])
        if y:
            sets[f'PR{y[1]}'] = {'jp': p['release_date'], 'en': None, 'approximate': True}
    pr_cards = {}
    for y in ['11', '12', '13', '14']:
        lst = json.load(open(f'data/raw/decks/pr-20{y}.json', encoding='utf-8'))
        if len(lst['items']) != lst['total']:
            raise SystemExit(f'PR 20{y}: got {len(lst["items"])} of {lst["total"]} cards')
        for i in lst['items']:
            pr_cards.setdefault(i['card_name'], f'PR{y}')
    out = {
        'prCards': dict(sorted(pr_cards.items())),
        'note': 'Release date of each set by region. Japanese dates: the official card list API (/manage/card-list-user/products). English dates are still to be researched: null means unknown, and a card cannot be checked against an English cutoff until it is filled in. A PR list is dated by its year only (approximate): the official data gives no date per card. `prCards`: Japanese card name → the first yearly PR list that has it.',
        'sets': dict(sorted(sets.items())),
    }
    json.dump(out, open('data/releases.json', 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=2)
    return len(sets)


def main():
    n = build_releases()
    candidates = json.load(open('data/raw/decks/candidates.json', encoding='utf-8'))
    selection = json.load(open('data/decks/selection.json', encoding='utf-8'))
    decks, problems = [], []
    for sel in selection['decks']:
        if 'manual' in sel:
            decks.append(sel['manual'])
            continue
        that_day = [c for c in candidates if c['date'] == sel['published']]
        if sel['ordinal'] >= len(that_day):
            problems.append(f"{sel['id']}: no list {sel['ordinal']} on {sel['published']}")
            continue
        c = that_day[sel['ordinal']]
        if c['unresolved']:
            problems.append(f"{sel['id']}: unresolved names {[u['name'] for u in c['unresolved']]}")
            continue
        names = {r['name'] for r in c['cards']}
        for must in sel['mustInclude']:
            if must not in names:
                problems.append(f"{sel['id']}: expected {must} in the list")
        fv = next((r for r in c['cards'] if r['fv']), None) or next(
            (r for r in c['cards'] if r['grade'] == 0 and r['trigger'] is None), None
        )
        if fv is None:
            problems.append(f"{sel['id']}: no first vanguard")
            continue
        merged = {}
        for r in c['cards']:
            e = merged.setdefault(r['id'], {'id': r['id'], 'count': 0, 'sourceName': r['name']})
            e['count'] += r['count']
        decks.append({
            'id': sel['id'],
            'name': sel['name'],
            'clan': c['clan'],
            'archetype': sel['archetype'],
            'format': 'classic',
            'region': sel['region'],
            'cutoff': sel['cutoff'],
            'version': 1,
            'confidence': sel['confidence'],
            # no player names: the month's archive, not the post's address or title
            'sources': [{
                'url': 'https://vanguardus.blogspot.com/' + c['date'][:7].replace('-', '/') + '/',
                'title': 'vanguardus blog, tournament report or player spotlight',
                'published': c['date'],
                'kind': 'contemporary report',
            }],
            'tournament': sel.get('tournament'),
            'note': sel.get('note'),
            'firstVanguard': fv['id'],
            'cards': list(merged.values()),
        })
    if problems:
        print('\n'.join(problems))
        return 1
    out = {'note': 'Generated by scripts/decks/buildLibrary.py. Do not edit by hand.', 'decks': decks}
    json.dump(out, open('data/decks/library.json', 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
    print(f'{n} sets dated, {len(decks)} decks written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
