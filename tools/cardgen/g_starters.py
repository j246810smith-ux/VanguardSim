"""Write src/decks/gStarters.ts: one legal starter deck per clan of G-BT03 to G-BT05 without a G Trial Deck.

    python tools/cardgen/g_starters.py <repo>

Our own builds, not products. The clan's cards of the deck's set come first, then its other G-era
cards, then its Classic ones: 1 first vanguard, 16 triggers (4 heals), 14 grade 1 (4 sentinels),
11 grade 2, 8 grade 3, and up to 16 G units (4 per name).
"""
import glob
import json
import os
import sys

repo = sys.argv[1]
DECKS = [
    ('G-BT03', 'Shadow Paladin'), ('G-BT03', 'Gold Paladin'), ('G-BT03', 'Murakumo'),
    ('G-BT03', 'Dark Irregulars'), ('G-BT03', 'Kagero'), ('G-BT04', 'Angel Feather'),
    ('G-BT04', 'Genesis'), ('G-BT04', 'Megacolony'), ('G-BT05', 'Pale Moon'),
    ('G-BT05', 'Oracle Think Tank'), ('G-BT05', 'Narukami'),
]
SET_ORDER = ['G-BT05', 'G-BT04', 'G-BT03', 'G-BT02', 'G-BT01', 'G-TD05', 'G-TD04', 'G-TD03', 'G-TD02', 'G-TD01']
pool = []
for f in glob.glob(os.path.join(repo, 'data', 'cards', '*.json')):
    if f.endswith('status.json'):
        continue
    d = json.load(open(f, encoding='utf8'))
    if d['set'].startswith('PR') or d['set'] == 'VZ01':
        continue
    pool += [c for c in d['cards'] if c.get('en') and not c['id'].endswith('EN')]


def rank(card, home):
    s = card['set']
    if s == home:
        return (0, card['id'])
    if s in SET_ORDER:
        return (1 + SET_ORDER.index(s), card['id'])
    return (50, card['id'])


out = []
for home, clan in DECKS:
    mine = sorted([c for c in pool if c['en']['clan'] == clan], key=lambda c: rank(c, home))
    seen, unique = set(), []
    for c in mine:
        if c['en']['name'] not in seen:
            seen.add(c['en']['name'])
            unique.append(c)
    main = [c for c in unique if c['cardType'] != 'g_unit']
    cards = []

    def take(cands, total, per=4):
        got = 0
        for c in cands:
            n = min(per, total - got)
            if n <= 0:
                break
            cards.extend([c['id']] * n)
            got += n
        assert got == total, (clan, total, got)

    first = next(c for c in main if c['grade'] == 0 and not c['trigger'])
    cards.append(first['id'])
    trig = [c for c in main if c['grade'] == 0 and c['trigger']]
    take([c for c in trig if c['trigger'] == 'heal'], 4)
    take([c for c in trig if c['trigger'] != 'heal'], 12)
    plain = lambda g: [c for c in main if c['grade'] == g and not c['trigger'] and not c['sentinel']]
    sentinels = [c for c in main if c['sentinel'] and c['grade'] == 1]
    take(sentinels, 4)
    take(plain(1), 10)
    take(plain(2), 11)
    take(plain(3), 8)
    g_units = [c for c in unique if c['cardType'] == 'g_unit' and c['grade'] == 4]
    g_deck = []
    for c in g_units[:4]:
        g_deck.extend([c['id']] * 4)
    out.append((home, clan, first['id'], cards, g_deck[:16]))
    assert len(cards) == 50, (clan, len(cards))

lines = [
    '/**',
    ' * Starter decks for the clans of G-BT03 to G-BT05 without a G Trial Deck (G format). Our own builds,',
    ' * not official products. Generated by tools/cardgen/g_starters.py.',
    ' */',
    "import type { StarterDeck } from './starters';",
    '',
    'const deck = (set: string, clan: string, firstVanguard: string, cards: string[], gDeck: string[]): StarterDeck => ({',
    "  name: `${set} · ${clan}`,",
    "  description: `Starter deck (${clan}): our own build around ${set}, not an official product.`,",
    '  deck: { firstVanguard, cards, gDeck },',
    "  format: 'g',",
    '});',
    '',
    'export const G_STARTER_DECKS: readonly StarterDeck[] = [',
]
for home, clan, first, cards, g in out:
    lines.append(f"  deck({json.dumps(home)}, {json.dumps(clan)}, {json.dumps(first)}, {json.dumps(cards)}, {json.dumps(g)}),")
lines += ['];', '']
open(os.path.join(repo, 'src', 'decks', 'gStarters.ts'), 'w', encoding='utf8', newline='').write('\n'.join(lines))
print(len(out), 'decks')
